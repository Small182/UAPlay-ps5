/* Desktop-only keyboard -> SDL virtual controller. */
#include "virtual_pad.h"
#include <stdio.h>
#include <string.h>

static SDL_GameController *controller;
static SDL_Joystick *joystick;
static Uint8 held[SDL_NUM_SCANCODES];
static SDL_JoystickID instance=-1;
typedef struct { SDL_Scancode key; SDL_GameControllerButton button; } Binding;
static const Binding buttons[]={
    {SDL_SCANCODE_UP,SDL_CONTROLLER_BUTTON_DPAD_UP},
    {SDL_SCANCODE_DOWN,SDL_CONTROLLER_BUTTON_DPAD_DOWN},
    {SDL_SCANCODE_LEFT,SDL_CONTROLLER_BUTTON_DPAD_LEFT},
    {SDL_SCANCODE_RIGHT,SDL_CONTROLLER_BUTTON_DPAD_RIGHT},
    {SDL_SCANCODE_RETURN,SDL_CONTROLLER_BUTTON_A},
    {SDL_SCANCODE_SPACE,SDL_CONTROLLER_BUTTON_A},
    {SDL_SCANCODE_BACKSPACE,SDL_CONTROLLER_BUTTON_B},
    {SDL_SCANCODE_ESCAPE,SDL_CONTROLLER_BUTTON_B},
    {SDL_SCANCODE_X,SDL_CONTROLLER_BUTTON_X},
    {SDL_SCANCODE_Y,SDL_CONTROLLER_BUTTON_Y},
    {SDL_SCANCODE_Q,SDL_CONTROLLER_BUTTON_LEFTSHOULDER},
    {SDL_SCANCODE_E,SDL_CONTROLLER_BUTTON_RIGHTSHOULDER},
    {SDL_SCANCODE_TAB,SDL_CONTROLLER_BUTTON_RIGHTSHOULDER},
    {SDL_SCANCODE_M,SDL_CONTROLLER_BUTTON_START},
    {SDL_SCANCODE_C,SDL_CONTROLLER_BUTTON_LEFTSTICK},
    {SDL_SCANCODE_V,SDL_CONTROLLER_BUTTON_RIGHTSTICK},
    {SDL_SCANCODE_T,SDL_CONTROLLER_BUTTON_TOUCHPAD}
};
static const struct {SDL_Scancode neg,pos; SDL_GameControllerAxis axis;} axes[]={
    {SDL_SCANCODE_A,SDL_SCANCODE_D,SDL_CONTROLLER_AXIS_LEFTX},
    {SDL_SCANCODE_W,SDL_SCANCODE_S,SDL_CONTROLLER_AXIS_LEFTY},
    {SDL_SCANCODE_J,SDL_SCANCODE_L,SDL_CONTROLLER_AXIS_RIGHTX},
    {SDL_SCANCODE_I,SDL_SCANCODE_K,SDL_CONTROLLER_AXIS_RIGHTY}
};
static int button_for(SDL_Scancode key){
    for(unsigned i=0;i<sizeof(buttons)/sizeof(buttons[0]);i++)
        if(buttons[i].key==key)return buttons[i].button;
    return -1;
}
static int axis_key(SDL_Scancode key){
    for(unsigned i=0;i<sizeof(axes)/sizeof(axes[0]);i++)
        if(axes[i].neg==key||axes[i].pos==key)return 1;
    return key==SDL_SCANCODE_1||key==SDL_SCANCODE_2;
}
static void sync_pad(void){
    if(!joystick)return;
    Uint8 state[SDL_CONTROLLER_BUTTON_MAX]={0};
    for(unsigned i=0;i<sizeof(buttons)/sizeof(buttons[0]);i++)
        if(held[buttons[i].key])state[buttons[i].button]=1;
    for(int i=0;i<SDL_CONTROLLER_BUTTON_MAX;i++)
        SDL_JoystickSetVirtualButton(joystick,i,state[i]);
    for(unsigned i=0;i<sizeof(axes)/sizeof(axes[0]);i++){
        int v=(int)held[axes[i].pos]-(int)held[axes[i].neg];
        SDL_JoystickSetVirtualAxis(joystick,axes[i].axis,(Sint16)(v*32767));
    }
    SDL_JoystickSetVirtualAxis(joystick,SDL_CONTROLLER_AXIS_TRIGGERLEFT,held[SDL_SCANCODE_1]?32767:-32768);
    SDL_JoystickSetVirtualAxis(joystick,SDL_CONTROLLER_AXIS_TRIGGERRIGHT,held[SDL_SCANCODE_2]?32767:-32768);
    SDL_JoystickUpdate();
}
SDL_GameController *preview_pad_open(void){
    if(controller)return controller;
    if(SDL_InitSubSystem(SDL_INIT_GAMECONTROLLER)<0)return NULL;
    SDL_SetHint(SDL_HINT_JOYSTICK_ALLOW_BACKGROUND_EVENTS,"1");
    SDL_VirtualJoystickDesc desc={0};
    desc.version=SDL_VIRTUAL_JOYSTICK_DESC_VERSION;
    desc.type=SDL_JOYSTICK_TYPE_GAMECONTROLLER;
    desc.naxes=SDL_CONTROLLER_AXIS_MAX;
    desc.nbuttons=SDL_CONTROLLER_BUTTON_MAX;
    desc.name="UAPlay virtual DualSense (keyboard)";
    desc.vendor_id=0x1209;desc.product_id=0x3605;
    desc.axis_mask=(1u<<SDL_CONTROLLER_AXIS_MAX)-1u;
    desc.button_mask=(1u<<SDL_CONTROLLER_BUTTON_MAX)-1u;
    int index=SDL_JoystickAttachVirtualEx(&desc);
    if(index<0)return NULL;
    controller=SDL_GameControllerOpen(index);
    if(!controller){SDL_JoystickDetachVirtual(index);return NULL;}
    joystick=SDL_GameControllerGetJoystick(controller);
    instance=SDL_JoystickInstanceID(joystick);
    memset(held,0,sizeof(held));sync_pad();
    return controller;
}
int preview_pad_owns(SDL_GameController *pad){return pad&&pad==controller;}
void preview_pad_close(void){
    if(!controller)return;
    memset(held,0,sizeof(held));sync_pad();
    int index=-1;
    for(int i=0;i<SDL_NumJoysticks();i++)if(SDL_JoystickGetDeviceInstanceID(i)==instance){index=i;break;}
    SDL_GameControllerClose(controller);controller=NULL;joystick=NULL;instance=-1;
    if(index>=0)SDL_JoystickDetachVirtual(index);
}
static int translate(const SDL_Event *e){
    if(!controller)return 0;
    if(e->type==SDL_WINDOWEVENT&&e->window.event==SDL_WINDOWEVENT_FOCUS_LOST){
        memset(held,0,sizeof(held));sync_pad();return 0;
    }
    if(e->type!=SDL_KEYDOWN&&e->type!=SDL_KEYUP)return 0;
    SDL_Scancode key=e->key.keysym.scancode;
    /* Synthetic seek events generated by the shared stick handler carry
       UNKNOWN scancodes. Pass them through, never feed them back to the pad. */
    if(key<=SDL_SCANCODE_UNKNOWN||key>=SDL_NUM_SCANCODES)return 0;
    if(key==SDL_SCANCODE_F1){
        if(e->type==SDL_KEYDOWN&&!e->key.repeat){
            memset(held,0,sizeof(held));sync_pad();
            SDL_ShowSimpleMessageBox(SDL_MESSAGEBOX_INFORMATION,"UAPlay - keyboard controller",
              "Arrows: D-pad\nEnter / Space: Cross    Backspace / Esc: Circle\n"
              "X: Square    Y: Triangle    M: Options\nQ / E: L1 / R1    1 / 2: L2 / R2\n"
              "WASD: left stick    IJKL: right stick\nC / V: L3 / R3    T: Touchpad",NULL);
        }
        return 1;
    }
    if(button_for(key)<0&&!axis_key(key))return 0;
    held[key]=e->type==SDL_KEYDOWN;
    sync_pad();
    return 1;
}
int preview_poll_event(SDL_Event *e){
    while(SDL_PollEvent(e)){if(!translate(e))return 1;}
    return 0;
}
static void fake_key(SDL_Scancode key,int down){
    SDL_Event e={0};e.type=down?SDL_KEYDOWN:SDL_KEYUP;e.key.keysym.scancode=key;
    e.key.keysym.sym=SDL_GetKeyFromScancode(key);translate(&e);
}
int preview_pad_selftest(void){
    SDL_GameController *pad=preview_pad_open();
    if(!pad){fprintf(stderr,"[preview] virtual pad: FAIL (%s)\n",SDL_GetError());return 0;}
    SDL_Event e;while(SDL_PollEvent(&e)){}
    fake_key(SDL_SCANCODE_RETURN,1);
    int down=0;while(SDL_PollEvent(&e))if(e.type==SDL_CONTROLLERBUTTONDOWN&&e.cbutton.which==instance&&e.cbutton.button==SDL_CONTROLLER_BUTTON_A)down=1;
    int ok=down&&SDL_GameControllerGetButton(pad,SDL_CONTROLLER_BUTTON_A);
    fake_key(SDL_SCANCODE_SPACE,1);fake_key(SDL_SCANCODE_RETURN,0);
    ok &= SDL_GameControllerGetButton(pad,SDL_CONTROLLER_BUTTON_A)!=0;
    fake_key(SDL_SCANCODE_SPACE,0);
    int up=0;while(SDL_PollEvent(&e))if(e.type==SDL_CONTROLLERBUTTONUP&&e.cbutton.which==instance&&e.cbutton.button==SDL_CONTROLLER_BUTTON_A)up=1;
    ok &= up&&!SDL_GameControllerGetButton(pad,SDL_CONTROLLER_BUTTON_A);
    fake_key(SDL_SCANCODE_D,1);fake_key(SDL_SCANCODE_I,1);
    ok &= SDL_GameControllerGetAxis(pad,SDL_CONTROLLER_AXIS_LEFTX)>19000;
    ok &= SDL_GameControllerGetAxis(pad,SDL_CONTROLLER_AXIS_RIGHTY)<-19000;
    fake_key(SDL_SCANCODE_A,1);
    ok &= SDL_GameControllerGetAxis(pad,SDL_CONTROLLER_AXIS_LEFTX)==0;
    fake_key(SDL_SCANCODE_Q,1);fake_key(SDL_SCANCODE_E,1);
    ok &= SDL_GameControllerGetButton(pad,SDL_CONTROLLER_BUTTON_LEFTSHOULDER)!=0;
    ok &= SDL_GameControllerGetButton(pad,SDL_CONTROLLER_BUTTON_RIGHTSHOULDER)!=0;
    e.type=SDL_WINDOWEVENT;e.window.event=SDL_WINDOWEVENT_FOCUS_LOST;translate(&e);
    ok &= SDL_GameControllerGetAxis(pad,SDL_CONTROLLER_AXIS_RIGHTY)==0;
    ok &= SDL_GameControllerGetAxis(pad,SDL_CONTROLLER_AXIS_LEFTX)==0;
    ok &= !SDL_GameControllerGetButton(pad,SDL_CONTROLLER_BUTTON_LEFTSHOULDER);
    preview_pad_close();
    fprintf(stderr,"[preview] keyboard virtual controller: %s\n",ok?"PASS":"FAIL");return ok;
}
